CREATE TABLE IF NOT EXISTS public.specialities(
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  specialist_title TEXT NOT NULL UNIQUE
);
DO $$
BEGIN
  -- Seed only titles that are missing. Written without ON CONFLICT so it also works
  -- when specialities already exists without a unique constraint.
  INSERT INTO public.specialities(specialist_title)
    SELECT t FROM (VALUES ('General Practice'),('Internal Medicine'),('Paediatrics'),('Obstetrics and Gynaecology'),('Surgery')) AS v(t)
    WHERE NOT EXISTS (SELECT 1 FROM public.specialities x WHERE x.specialist_title = v.t);
EXCEPTION WHEN OTHERS THEN
  RAISE NOTICE 'Skipped seeding specialities: %', SQLERRM;
END $$;

-- Doctor working hours: one row per doctor per weekday (0 = Sunday ... 6 = Saturday).
CREATE TABLE IF NOT EXISTS public.doctor_schedules(
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  doctor_id INTEGER NOT NULL REFERENCES public.users(id) ON DELETE CASCADE,
  weekday SMALLINT NOT NULL CHECK(weekday BETWEEN 0 AND 6),
  start_time TIME NOT NULL,
  end_time TIME NOT NULL,
  slot_minutes SMALLINT NOT NULL DEFAULT 30 CHECK(slot_minutes IN (10,15,20,30,45,60)),
  UNIQUE(doctor_id, weekday),
  CHECK(end_time > start_time)
);
-- Existing doctors get Monday-Friday 08:00-17:00 until an Admin changes it.
INSERT INTO public.doctor_schedules(doctor_id,weekday,start_time,end_time,slot_minutes)
  SELECT u.id, d, '08:00'::time, '17:00'::time, 30 FROM public.users u CROSS JOIN generate_series(1,5) AS d
  WHERE u.role='Doctor'
    AND NOT EXISTS (SELECT 1 FROM public.doctor_schedules s WHERE s.doctor_id=u.id AND s.weekday=d);

