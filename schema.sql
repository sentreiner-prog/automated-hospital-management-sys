CREATE OR REPLACE FUNCTION public.app_create_patient(
  p_name TEXT, p_date_of_birth DATE, p_age SMALLINT, p_sex TEXT, p_phone TEXT,
  p_next_of_kin TEXT, p_allergies JSONB, p_conditions JSONB, p_user_id INTEGER
) RETURNS TEXT
LANGUAGE plpgsql SECURITY DEFINER SET search_path = public AS $$
DECLARE
  patient_id TEXT;
BEGIN
  PERFORM pg_advisory_xact_lock(73015001);
  SELECT 'P-' || LPAD((COALESCE(MAX(SUBSTRING(id FROM 3)::INTEGER), 0) + 1)::TEXT, 3, '0')
    INTO patient_id FROM patients;
  INSERT INTO patients(id,name,age,date_of_birth,sex,phone,next_of_kin,allergies,conditions)
    VALUES(patient_id,p_name,p_age,p_date_of_birth,p_sex,p_phone,p_next_of_kin,p_allergies,p_conditions);
  INSERT INTO audit_log(user_id,action,detail) VALUES(p_user_id,'patient_created',patient_id);
  RETURN patient_id;
END;
$$;

