$$;

CREATE OR REPLACE FUNCTION public.app_dispense_prescription(
  p_prescription_id BIGINT, p_stock_id BIGINT, p_qty INTEGER, p_user_id INTEGER
) RETURNS VOID
LANGUAGE plpgsql SECURITY DEFINER SET search_path = public AS $$
DECLARE
  stock_item stock%ROWTYPE;
  prescription_row prescriptions%ROWTYPE;
BEGIN
  IF p_qty <= 0 THEN
    RAISE EXCEPTION 'Enter a quantity above zero.' USING ERRCODE='22023';
  END IF;
  SELECT * INTO prescription_row FROM prescriptions WHERE id=p_prescription_id FOR UPDATE;
  IF NOT FOUND OR prescription_row.status <> 'Pending' THEN
    RAISE EXCEPTION 'Prescription is not pending.' USING ERRCODE='P0002';
  END IF;
  SELECT * INTO stock_item FROM stock WHERE id=p_stock_id FOR UPDATE;
  IF NOT FOUND OR lower(stock_item.item) <> lower(prescription_row.drug) THEN
    RAISE EXCEPTION 'Choose the stock item prescribed.' USING ERRCODE='22023';
  END IF;
  IF stock_item.expiry IS NOT NULL AND stock_item.expiry < CURRENT_DATE THEN
    RAISE EXCEPTION 'Expired stock cannot be dispensed.' USING ERRCODE='P0001';
  END IF;
  IF stock_item.qty < p_qty THEN
    RAISE EXCEPTION 'Insufficient stock.' USING ERRCODE='P0001';
  END IF;
  UPDATE stock SET qty=qty-p_qty WHERE id=p_stock_id;
  UPDATE prescriptions SET status='Dispensed' WHERE id=p_prescription_id;
  INSERT INTO pharmacy_dispenses(prescription_id,stock_id,quantity,dispensed_by)
    VALUES(p_prescription_id,p_stock_id,p_qty,p_user_id);
  INSERT INTO audit_log(user_id,action,detail)
    VALUES(p_user_id,'prescription_dispensed',p_prescription_id::TEXT || ' qty=' || p_qty::TEXT);
END;
$$;

CREATE OR REPLACE FUNCTION public.app_admit_patient(
  p_patient_id TEXT, p_ward_id BIGINT, p_user_id INTEGER
) RETURNS BIGINT
LANGUAGE plpgsql SECURITY DEFINER SET search_path = public AS $$
DECLARE
  ward_row wards%ROWTYPE;
  admission_id BIGINT;
BEGIN
  SELECT * INTO ward_row FROM wards WHERE id=p_ward_id AND active=TRUE FOR UPDATE;
  IF NOT FOUND THEN RAISE EXCEPTION 'Ward is not available.' USING ERRCODE='P0002'; END IF;
  IF EXISTS(SELECT 1 FROM admissions WHERE patient_id=p_patient_id AND discharged_at IS NULL) THEN
    RAISE EXCEPTION 'Patient already has an active admission.' USING ERRCODE='23505';
  END IF;
  IF (SELECT count(*) FROM admissions WHERE ward_id=p_ward_id AND discharged_at IS NULL) >= ward_row.capacity THEN
    RAISE EXCEPTION 'Ward has reached capacity.' USING ERRCODE='P0001';
  END IF;
  INSERT INTO admissions(patient_id,ward_id,admitted_by)
    VALUES(p_patient_id,p_ward_id,p_user_id) RETURNING id INTO admission_id;
  INSERT INTO audit_log(user_id,action,detail)
    VALUES(p_user_id,'patient_admitted',admission_id::TEXT);
  RETURN admission_id;
END;
$$;

CREATE OR REPLACE FUNCTION public.app_seed_demo_data(p_data JSONB)
RETURNS VOID
LANGUAGE plpgsql SECURITY DEFINER SET search_path = public AS $$
DECLARE
  table_name TEXT;
  table_is_not_empty BOOLEAN;
BEGIN
  FOREACH table_name IN ARRAY ARRAY['patients','users','appointments','consultations','prescriptions','invoices','stock','audit_log'] LOOP
    EXECUTE format('SELECT EXISTS(SELECT 1 FROM public.%I)',table_name) INTO table_is_not_empty;
    IF table_is_not_empty THEN
      RAISE EXCEPTION 'Supabase table % is not empty; refusing to seed demo records.',table_name;
    END IF;
  END LOOP;
  INSERT INTO patients(id,name,age,sex,phone,next_of_kin,allergies,conditions)
    SELECT id,name,age,sex,phone,next_of_kin,allergies,conditions
    FROM jsonb_to_recordset(p_data->'patients') AS x(id TEXT,name TEXT,age SMALLINT,sex TEXT,phone TEXT,next_of_kin TEXT,allergies JSONB,conditions JSONB);
  INSERT INTO users(name,email,password_hash,role,specialty,patient_id)
    SELECT name,email,password_hash,role,specialty,patient_id
    FROM jsonb_to_recordset(p_data->'users') AS x(name TEXT,email TEXT,password_hash TEXT,role TEXT,specialty TEXT,patient_id TEXT);
  INSERT INTO appointments(patient_id,doctor,date,time,type,status)
    SELECT patient_id,doctor,date,time,type,status
    FROM jsonb_to_recordset(p_data->'appointments') AS x(patient_id TEXT,doctor TEXT,date DATE,time TEXT,type TEXT,status TEXT);
  INSERT INTO consultations(patient_id,doctor,date,diagnosis,notes)
    SELECT patient_id,doctor,date,diagnosis,notes
    FROM jsonb_to_recordset(p_data->'consultations') AS x(patient_id TEXT,doctor TEXT,date DATE,diagnosis TEXT,notes TEXT);
  INSERT INTO prescriptions(patient_id,drug,dose,doctor,date)
    SELECT patient_id,drug,dose,doctor,date
    FROM jsonb_to_recordset(p_data->'prescriptions') AS x(patient_id TEXT,drug TEXT,dose TEXT,doctor TEXT,date DATE);
  INSERT INTO invoices(id,patient_id,items,amount,paid)
    SELECT id,patient_id,items,amount,paid
    FROM jsonb_to_recordset(p_data->'invoices') AS x(id TEXT,patient_id TEXT,items TEXT,amount INTEGER,paid BOOLEAN);
  INSERT INTO stock(item,qty,reorder_level,expiry,supplier)
    SELECT item,qty,reorder_level,expiry,supplier
    FROM jsonb_to_recordset(p_data->'stock') AS x(item TEXT,qty INTEGER,reorder_level INTEGER,expiry DATE,supplier TEXT);
END;
$$;

CREATE OR REPLACE FUNCTION public.app_import_sqlite_data(p_data JSONB)
RETURNS VOID
LANGUAGE plpgsql SECURITY DEFINER SET search_path = public AS $$
DECLARE
  table_name TEXT;
  sequence_name TEXT;
  table_is_not_empty BOOLEAN;
BEGIN
  PERFORM pg_advisory_xact_lock(73015003);
  FOREACH table_name IN ARRAY ARRAY['patients','users','appointments','consultations','prescriptions','invoices','stock','audit_log'] LOOP
    EXECUTE format('SELECT EXISTS(SELECT 1 FROM public.%I)',table_name) INTO table_is_not_empty;
    IF table_is_not_empty THEN
      RAISE EXCEPTION 'Supabase table % is not empty; refusing to merge SQLite data into it.',table_name;
    END IF;
  END LOOP;

  INSERT INTO patients(id,name,age,date_of_birth,sex,phone,next_of_kin,allergies,conditions,created_at)
    SELECT id,name,age,date_of_birth,sex,phone,next_of_kin,allergies,conditions,created_at
    FROM jsonb_to_recordset(p_data->'patients') AS x(id TEXT,name TEXT,age SMALLINT,date_of_birth DATE,sex TEXT,phone TEXT,next_of_kin TEXT,allergies JSONB,conditions JSONB,created_at TIMESTAMPTZ);
  INSERT INTO users(id,name,email,password_hash,role,specialty,active,failed_attempts,locked_until,patient_id)
    SELECT id,name,email,password_hash,role,specialty,active,failed_attempts,locked_until,patient_id
    FROM jsonb_to_recordset(p_data->'users') AS x(id INTEGER,name TEXT,email TEXT,password_hash TEXT,role TEXT,specialty TEXT,active BOOLEAN,failed_attempts INTEGER,locked_until TIMESTAMPTZ,patient_id TEXT);
  INSERT INTO appointments(id,patient_id,doctor,date,time,type,status)
    SELECT id,patient_id,doctor,date,time,type,status
    FROM jsonb_to_recordset(p_data->'appointments') AS x(id BIGINT,patient_id TEXT,doctor TEXT,date DATE,time TEXT,type TEXT,status TEXT);
  INSERT INTO consultations(id,patient_id,doctor,date,diagnosis,notes)
    SELECT id,patient_id,doctor,date,diagnosis,notes
    FROM jsonb_to_recordset(p_data->'consultations') AS x(id BIGINT,patient_id TEXT,doctor TEXT,date DATE,diagnosis TEXT,notes TEXT);
  INSERT INTO prescriptions(id,patient_id,drug,dose,doctor,date)
    SELECT id,patient_id,drug,dose,doctor,date
    FROM jsonb_to_recordset(p_data->'prescriptions') AS x(id BIGINT,patient_id TEXT,drug TEXT,dose TEXT,doctor TEXT,date DATE);
  INSERT INTO invoices(id,patient_id,items,amount,paid,method,paid_at)
    SELECT id,patient_id,items,amount,paid,method,paid_at
    FROM jsonb_to_recordset(p_data->'invoices') AS x(id TEXT,patient_id TEXT,items TEXT,amount INTEGER,paid BOOLEAN,method TEXT,paid_at TIMESTAMPTZ);
  INSERT INTO stock(id,item,qty,reorder_level,expiry,supplier)
    SELECT id,item,qty,reorder_level,expiry,supplier
    FROM jsonb_to_recordset(p_data->'stock') AS x(id BIGINT,item TEXT,qty INTEGER,reorder_level INTEGER,expiry DATE,supplier TEXT);
  INSERT INTO audit_log(id,user_id,action,detail,at)
    SELECT id,user_id,action,detail,at
    FROM jsonb_to_recordset(p_data->'audit_log') AS x(id BIGINT,user_id INTEGER,action TEXT,detail TEXT,at TIMESTAMPTZ);

  FOREACH table_name IN ARRAY ARRAY['users','appointments','consultations','prescriptions','stock','audit_log'] LOOP
    sequence_name:=pg_get_serial_sequence('public.'||table_name,'id');
    IF sequence_name IS NOT NULL THEN
      EXECUTE format('SELECT setval(%L::regclass,COALESCE((SELECT MAX(id) FROM public.%I),1),EXISTS(SELECT 1 FROM public.%I))',sequence_name,table_name,table_name);
    END IF;
  END LOOP;
END;
$$;

