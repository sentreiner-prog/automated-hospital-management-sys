CREATE OR REPLACE FUNCTION public.app_book_appointment(
  p_patient_id TEXT, p_doctor TEXT, p_date DATE, p_time TEXT, p_type TEXT, p_user_id INTEGER
) RETURNS BIGINT
LANGUAGE plpgsql SECURITY DEFINER SET search_path = public AS $$
DECLARE
  appointment_id BIGINT;
  sched doctor_schedules%ROWTYPE;
  slot_start TIME;
BEGIN
  IF p_date < CURRENT_DATE THEN
    RAISE EXCEPTION 'Appointments cannot be booked in the past.' USING ERRCODE='P0005';
  END IF;
  slot_start := p_time::TIME;
  SELECT s.* INTO sched FROM doctor_schedules s JOIN users u ON u.id=s.doctor_id
    WHERE u.name=p_doctor AND u.role='Doctor' AND s.weekday=EXTRACT(DOW FROM p_date)::SMALLINT;
  IF NOT FOUND THEN
    RAISE EXCEPTION 'Doctor is not scheduled to work on this day.' USING ERRCODE='P0003';
  END IF;
  IF slot_start < sched.start_time
     OR slot_start + make_interval(mins => sched.slot_minutes) > sched.end_time
     OR (EXTRACT(EPOCH FROM (slot_start - sched.start_time)) / 60)::INT % sched.slot_minutes <> 0 THEN
    RAISE EXCEPTION 'Time is outside the doctor working slots.' USING ERRCODE='P0004';
  END IF;
  PERFORM pg_advisory_xact_lock(hashtextextended(p_doctor || p_date::TEXT || p_time, 73015002));
  IF EXISTS (
    SELECT 1 FROM appointments
    WHERE doctor=p_doctor AND date=p_date AND time=p_time AND status NOT IN ('Missed','Cancelled')
  ) THEN
    RAISE EXCEPTION 'Appointment conflict' USING ERRCODE='23P01';
  END IF;
  INSERT INTO appointments(patient_id,doctor,date,time,type)
    VALUES(p_patient_id,p_doctor,p_date,p_time,p_type) RETURNING id INTO appointment_id;
  INSERT INTO audit_log(user_id,action,detail) VALUES(p_user_id,'appointment_booked',appointment_id::TEXT);
  RETURN appointment_id;
END;
$$;

