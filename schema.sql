CREATE OR REPLACE FUNCTION public.app_add_charge(
  p_patient_id TEXT, p_fee_id BIGINT, p_quantity INTEGER, p_visit_date DATE, p_source TEXT, p_note TEXT, p_user_id INTEGER
) RETURNS BIGINT
LANGUAGE plpgsql SECURITY DEFINER SET search_path = public AS $$
DECLARE
  fee fee_schedule%ROWTYPE;
  inv TEXT;
  line_id BIGINT;
BEGIN
  SELECT * INTO fee FROM fee_schedule WHERE id = p_fee_id AND active;
  IF NOT FOUND THEN RAISE EXCEPTION 'Fee not found or inactive.' USING ERRCODE='P0010'; END IF;
  PERFORM pg_advisory_xact_lock(73015002);
  -- once-only fees are charged one time per patient; per-visit fees once per patient per day
  IF fee.unit = 'once' AND EXISTS (SELECT 1 FROM invoice_lines WHERE patient_id=p_patient_id AND fee_id=fee.id) THEN RETURN NULL; END IF;
  IF fee.unit = 'visit' AND EXISTS (SELECT 1 FROM invoice_lines WHERE patient_id=p_patient_id AND fee_id=fee.id AND visit_date=p_visit_date) THEN RETURN NULL; END IF;
  -- add to the patient's open invoice, or start one
  SELECT id INTO inv FROM invoices WHERE patient_id=p_patient_id AND NOT paid ORDER BY SUBSTRING(id FROM 5)::INTEGER DESC LIMIT 1;
  IF inv IS NULL THEN
    SELECT 'INV-' || (COALESCE(MAX(SUBSTRING(id FROM 5)::INTEGER),1000)+1)::TEXT INTO inv FROM invoices;
    INSERT INTO invoices(id,patient_id,items,amount) VALUES(inv,p_patient_id,'Itemised bill',0);
  END IF;
  INSERT INTO invoice_lines(invoice_id,patient_id,fee_id,category,description,quantity,unit_price,amount,visit_date,source,created_by)
    VALUES(inv,p_patient_id,fee.id,fee.category, fee.name || COALESCE(' - ' || NULLIF(p_note,''),''), p_quantity, fee.amount, fee.amount*p_quantity, p_visit_date, p_source, p_user_id)
    RETURNING id INTO line_id;
  UPDATE invoices SET amount=(SELECT COALESCE(SUM(amount),0) FROM invoice_lines WHERE invoice_id=inv AND NOT waived) WHERE id=inv;
  INSERT INTO audit_log(user_id,action,detail) VALUES(p_user_id,'charge_added',inv || ': ' || fee.name || ' x' || p_quantity || ' (' || p_source || ')');
  RETURN line_id;
END;
$$;

CREATE OR REPLACE FUNCTION public.app_waive_line(p_line_id BIGINT, p_reason TEXT, p_user_id INTEGER)
RETURNS BOOLEAN
LANGUAGE plpgsql SECURITY DEFINER SET search_path = public AS $$
DECLARE
  inv TEXT;
BEGIN
  SELECT l.invoice_id INTO inv FROM invoice_lines l JOIN invoices i ON i.id=l.invoice_id
    WHERE l.id=p_line_id AND NOT l.waived AND NOT i.paid;
  IF inv IS NULL THEN RAISE EXCEPTION 'Charge not found, already waived, or already paid.' USING ERRCODE='P0011'; END IF;
  UPDATE invoice_lines SET waived=TRUE, waived_reason=p_reason WHERE id=p_line_id;
  UPDATE invoices SET amount=(SELECT COALESCE(SUM(amount),0) FROM invoice_lines WHERE invoice_id=inv AND NOT waived) WHERE id=inv;
  INSERT INTO audit_log(user_id,action,detail) VALUES(p_user_id,'charge_waived',inv || ' line ' || p_line_id || ': ' || p_reason);
  RETURN TRUE;
END;
$$;

